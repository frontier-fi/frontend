export function getYieldBearingTokenUrl({
  protocolId,
  chain,
  tokenAddress,
  underlyingAddress,
  underlyingSymbol,
}: {
  protocolId?: string
  chain: AppChain
  tokenAddress?: string | null
  underlyingAddress?: string | null
  underlyingSymbol?: string | null
}): string | undefined {
  if (!protocolId) return undefined

  if (protocolId === 'boosted_aave') {
    const marketName = AAVE_MARKET_NAME_BY_CHAIN[chain]

    if (underlyingAddress && marketName) {
      return `https://app.aave.com/reserve-overview/?underlyingAsset=${underlyingAddress.toLowerCase()}&marketName=${marketName}`
    }

    return undefined
  }

  if (protocolId === 'boosted_aave_pro') {
    return 'https://pro.aave.com/explore/earn'
  }

  if (protocolId === 'boosted_neverland') {
    return underlyingSymbol
      ? `https://app.neverland.money/markets?asset=${encodeURIComponent(underlyingSymbol.toLowerCase())}`
      : 'https://app.neverland.money/markets'
  }

  if (protocolId === 'boosted_euler') {
    const network = EULER_NETWORK_BY_CHAIN[chain]

    if (tokenAddress && network) {
      return `https://app.euler.finance/vault/${tokenAddress}?network=${network}`
    }

    return undefined
  }

  return undefined
}

export type YieldBearingPoolToken = Pick<GqlPoolTokenDetail, 'address' | 'underlyingToken'> & {
  nestedPool?: {
    tokens?: Pick<GqlPoolTokenDetail, 'address' | 'underlyingToken'>[]
  } | null
}

export interface MerklAprSubItem {
  id: string
  title: string
  apr: BigNumber
  opportunityId?: string
  opportunityUrl?: string
}

// Types that must be added to the total base (Frontier APR enum subset)
const TOTAL_BASE_APR_TYPES: GqlPoolAprItemType[] = [
  GqlPoolAprItemTypeValues.SwapFee24h,
  GqlPoolAprItemTypeValues.IbYield,
  GqlPoolAprItemTypeValues.Merkl,
  GqlPoolAprItemTypeValues.Surplus24h,
]

// Types that must be added to the total APR
export const TOTAL_APR_TYPES: GqlPoolAprItemType[] = [...TOTAL_BASE_APR_TYPES]

export function useAprTooltip({
  aprItems,
  numberFormatter,
  chain,
  poolTokens,
  getErc4626ProtocolId,
}: {
  aprItems: GqlPoolAprItem[]
  numberFormatter: (value: string) => BigNumber
  chain: AppChain
  poolTokens?: YieldBearingPoolToken[]
  getErc4626ProtocolId?: (chain: AppChain, tokenAddress: string) => string | undefined
}) {
  // Swap fees
  const swapFee = aprItems.find(item => item.type === GqlPoolAprItemTypeValues.SwapFee24h)
  const swapFeesDisplayed = numberFormatter(swapFee ? swapFee.apr.toString() : '0')

  // Dynamic swap fees
  const dynamicSwapFee = aprItems.find(
    item => item.type === GqlPoolAprItemTypeValues.DynamicSwapFee24h
  )

  const dynamicSwapFeesDisplayed = numberFormatter(
    dynamicSwapFee ? dynamicSwapFee.apr.toString() : '0'
  )

  // Yield bearing tokens
  const yieldBearingTokens = aprItems.filter(item => {
    return item.type === GqlPoolAprItemTypeValues.IbYield
  })

  const flattenedPoolTokens = poolTokens
    ? poolTokens.flatMap(token => [token, ...(token.nestedPool?.tokens ?? [])])
    : []

  const yieldBearingTokensDisplayed = yieldBearingTokens.map(item => {
    const tokenAddress = item.rewardTokenAddress?.toLowerCase()

    const matchingToken = tokenAddress
      ? flattenedPoolTokens.find(token => token.address.toLowerCase() === tokenAddress)
      : undefined

    const protocolId =
      tokenAddress && getErc4626ProtocolId ? getErc4626ProtocolId(chain, tokenAddress) : undefined

    const url = getYieldBearingTokenUrl({
      protocolId,
      chain,
      tokenAddress: matchingToken?.address ?? item.rewardTokenAddress,
      underlyingAddress: matchingToken?.underlyingToken?.address,
      underlyingSymbol: matchingToken?.underlyingToken?.symbol,
    })

    return {
      title: item.rewardTokenSymbol || '',
      apr: numberFormatter(item.apr.toString()),
      ...(url ? { url } : {}),
    }
  })

  const yieldBearingTokensAprDisplayed = yieldBearingTokensDisplayed.reduce(
    (acc, item) => acc.plus(item.apr),
    bn(0)
  )

  // Removed Frontier-unavailable APR types — return zeros for consumers that still expect them
  const stakingIncentivesDisplayed: {
    title: string
    apr: BigNumber
    tooltipText: string
  }[] = []

  const stakingIncentivesAprDisplayed = bn(0)
  const votingAprDisplayed = bn(0)
  const lockingAprDisplayed = bn(0)
  const quantAMMFeesDisplayed = bn(0)
  const fuulIncentivesDisplayed = bn(0)

  // Merkl incentives
  const merklIncentives = filterByType(aprItems, GqlPoolAprItemTypeValues.Merkl)
  const hasMerklIncentives = merklIncentives.length > 0
  const merklIncentivesAprDisplayed = calculateSingleIncentivesAprDisplayed(merklIncentives)

  const merklTokens = aprItems.filter(item => {
    return item.type === GqlPoolAprItemTypeValues.Merkl
  })

  const merklTokensDisplayed: MerklAprSubItem[] = merklTokens.map(item => {
    const opportunityId = getMerklOpportunityId(item.id)
    const opportunityUrl = opportunityId ? getMerklOpportunityUrl(opportunityId) : undefined

    return {
      id: item.id,
      title: opportunityId ? item.title : item.rewardTokenSymbol || '',
      apr: numberFormatter(item.apr.toString()),
      ...(opportunityId ? { opportunityId, opportunityUrl } : {}),
    }
  })

  // Surplus incentives
  const surplusIncentives = filterByType(aprItems, GqlPoolAprItemTypeValues.Surplus24h)
  const surplusIncentivesAprDisplayed = calculateSingleIncentivesAprDisplayed(surplusIncentives)

  const totalBase = aprItems
    .filter(item => TOTAL_BASE_APR_TYPES.includes(item.type))
    .reduce((acc, item) => acc.plus(item.apr), bn(0))

  const totalBaseDisplayed = numberFormatter(totalBase.toString())

  const totalCombined = aprItems
    .filter(item => TOTAL_APR_TYPES.includes(item.type))
    .reduce((acc, item) => acc.plus(item.apr), bn(0))

  const totalCombinedDisplayed = numberFormatter(totalCombined.toString())

  const isSwapFeePresent = !swapFeesDisplayed.isZero()
  const isYieldPresent = !yieldBearingTokensAprDisplayed.isZero()
  const isStakingPresent = stakingIncentivesAprDisplayed.gt(0)
  const isVotingPresent = false
  const isLockingAprPresent = false

  // gray.400 washes out on light beige tooltip backgrounds; darken in light mode.
  const subitemFontColor = useColorModeValue('gray.500', 'gray.400')

  const subitemPopoverAprItemProps = {
    pt: 2,
    pl: 'sm',
    backgroundColor: 'background.level1',
    fontWeight: 500,
    fontColor: subitemFontColor,
  }

  return {
    totalBaseDisplayed,
    yieldBearingTokensAprDisplayed,
    stakingIncentivesAprDisplayed,
    swapFeesDisplayed,
    isSwapFeePresent,
    isYieldPresent,
    isStakingPresent,
    yieldBearingTokensDisplayed,
    stakingIncentivesDisplayed,
    merklIncentivesAprDisplayed,
    merklTokensDisplayed,
    hasMerklIncentives,
    surplusIncentivesAprDisplayed,
    votingAprDisplayed,
    lockingAprDisplayed,
    isVotingPresent,
    isLockingAprPresent,
    subitemPopoverAprItemProps,
    totalBase,
    totalCombined,
    totalCombinedDisplayed,
    dynamicSwapFeesDisplayed,
    dynamicSwapFeesTooltipText,
    quantAMMTooltipText,
    quantAMMFeesDisplayed,
    fuulTooltipText,
    fuulIncentivesDisplayed,
  }
}

function filterByType(aprItems: GqlPoolAprItem[], type: GqlPoolAprItemType) {
  return aprItems.filter(item => {
    return item.type === type
  })
}

function calculateSingleIncentivesAprDisplayed(aprItems: GqlPoolAprItem[]) {
  return aprItems.reduce((acc, item) => acc.plus(item.apr), bn(0))
}
